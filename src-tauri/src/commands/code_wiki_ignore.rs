// Phase 0.5 — IGNORE. Generates a per-repo `.understandignore` file
// (mirrors UA's `.understandignore`) by reading the project's
// `.gitignore` and prepending language-grouped test/build defaults.
// The file lives at `wiki/code_wiki/<repo>/.understand/.understandignore`
// and is consulted by the scanner's filter pass to skip files the
// user wants excluded from analysis.
//
// Pattern format: one glob per line, `#` for comments. Lines starting
// with `!` re-include a previously-excluded pattern (negation).
//
// We intentionally do NOT shell out to `gitignore` parser crates —
// the input is a small file and the matching logic is delegated to
// the scanner (which already walks the tree and can check each
// candidate path against the list of glob literals). This keeps
// the dependency surface small.

